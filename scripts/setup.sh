#!/usr/bin/env bash
# One-shot setup: seed Supabase, create a read-only role for Anfra, and write
# .anfra/data_sources.yml so Anfra can query it.
#
# Usage:
#   export SUPABASE_DB_URL='postgresql://postgres.<project-ref>:<password>@aws-0-<region>.pooler.supabase.com:5432/postgres'
#   ./scripts/setup.sh
#
# (or put that URL alone in a git-ignored .env.local file)
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -z "${SUPABASE_DB_URL:-}" && -f .env.local ]]; then
  SUPABASE_DB_URL="$(grep -v '^\s*#' .env.local | sed -E 's/^SUPABASE_DB_URL=//; s/^["'\'']//; s/["'\'']$//' | head -n1)"
fi
: "${SUPABASE_DB_URL:?Set SUPABASE_DB_URL to your Supabase Session pooler connection string}"
command -v psql >/dev/null || { echo "psql is required (brew install libpq / apt install postgresql-client)"; exit 1; }

# Parse postgresql://user:password@host:port/dbname
re='^postgres(ql)?://([^:]+):([^@]+)@([^:/]+):?([0-9]*)/([^?]+)'
[[ "$SUPABASE_DB_URL" =~ $re ]] || { echo "Could not parse SUPABASE_DB_URL"; exit 1; }
admin_user="${BASH_REMATCH[2]}"
host="${BASH_REMATCH[4]}"
port="${BASH_REMATCH[5]:-5432}"
dbname="${BASH_REMATCH[6]}"

# On the Supabase pooler, users are written <role>.<project-ref>
project_ref=""
[[ "$admin_user" == *.* ]] && project_ref="${admin_user#*.}"
reader_user="anfra_reader${project_ref:+.$project_ref}"
# Reuse the password from a previous run: the Supabase pooler caches role
# credentials for a while, so rotating it on every run breaks the next login.
existing_password=""
if [[ -f .anfra/data_sources.yml ]]; then
  existing_password="$(awk '/^ *supabase:/{f=1} f && /^ *password:/{print $2; exit}' .anfra/data_sources.yml)"
  [[ "$existing_password" == "<password>" || "$existing_password" == "change-me" ]] && existing_password=""
fi
reader_password="${ANFRA_READER_PASSWORD:-${existing_password:-$(openssl rand -hex 16)}}"

echo "→ Seeding the ecommerce schema on $host"
psql "$SUPABASE_DB_URL" -v ON_ERROR_STOP=1 -q -f supabase/seed.sql

echo "→ Creating the read-only role anfra_reader"
psql "$SUPABASE_DB_URL" -v ON_ERROR_STOP=1 -q \
  -v reader_password="'$reader_password'" -f supabase/anfra_reader.sql

echo "→ Writing .anfra/data_sources.yml (git-ignored)"
umask 077
cat > .anfra/data_sources.yml <<YAML
# Generated by scripts/setup.sh. Holds credentials: git-ignored.
data_sources:
  supabase:
    type: postgresql
    connection:
      host: $host
      port: $port
      user: $reader_user
      password: $reader_password
      dbname: $dbname
    settings:
      require_ssl: true
YAML

echo "→ Checking the connection through Anfra"
# A new password can take a moment to reach the pooler: retry a few times.
for attempt in 1 2 3 4 5 6; do
  if out="$(anfra query --lang sql --data-source supabase 'select count(*) as orders from ecommerce.orders' 2>&1)" \
     && ! grep -q '^error:' <<<"$out"; then
    grep -A1 'records:' <<<"$out" | tail -n1 | sed -E 's/[ -]*"?([0-9]+)"?/  orders visible to anfra_reader: \1/'
    echo "✓ Done. Next: anfra validate && anfra serve"
    exit 0
  fi
  sleep 10
done
echo "$out"
echo "✗ Anfra could not query Supabase as $reader_user. See the error above."
exit 1
